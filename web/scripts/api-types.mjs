// Generates src/lib/api/schema.d.ts from the manager's OpenAPI contract (src/openapi.js).
// `--check` fails when the committed types no longer match the backend contract.
// openapi-typescript still declares a TypeScript 5 peer, so it runs isolated through npx.
import { execSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const web = fileURLToPath(new URL('..', import.meta.url));
const target = join(web, 'src', 'lib', 'api', 'schema.d.ts');
const contractModule = pathToFileURL(join(web, '..', 'src', 'openapi.js')).href;
// The backend module is plain JavaScript without type information.
// eslint-disable-next-line @typescript-eslint/no-unsafe-assignment
const { apiContract } = await import(contractModule);
const work = mkdtempSync(join(tmpdir(), 'driverhub-api-'));
try {
	const contract = join(work, 'openapi.json');
	const output = join(work, 'schema.d.ts');
	writeFileSync(contract, JSON.stringify(apiContract));
	// Every argument is a constant or a path inside a fresh temporary directory.
	execSync(
		`npx -y -p openapi-typescript@7.13.0 -p typescript@5.9 openapi-typescript "${contract}" -o "${output}"`,
		{ stdio: ['ignore', 'ignore', 'inherit'] }
	);
	const header = '// Generated by scripts/api-types.mjs from src/openapi.js. Do not edit.\n';
	const generated = header + readFileSync(output, 'utf8').replace(/\r\n/g, '\n');
	if (process.argv.includes('--check')) {
		let current = '';
		try {
			current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
		} catch {
			// A missing file is simply out of date.
		}
		if (current !== generated) {
			console.error('src/lib/api/schema.d.ts is out of date. Run: npm run api:types');
			process.exit(1);
		}
		console.log('API types match the backend contract.');
	} else {
		writeFileSync(target, generated);
		console.log('Wrote src/lib/api/schema.d.ts');
	}
} finally {
	rmSync(work, { recursive: true, force: true });
}
